import { InvestigationSession } from '../types/forensics';

export function generateMarkdownReport(session: InvestigationSession): string {
  const dateStr = new Date(session.timestamp).toUTCString();

  return `# DroidForensics — APK Behavioral Forensics & Modification Report
**Generated:** ${dateStr}  
**Session ID:** \`${session.id}\`  
**Target Behavior:** \`${session.targetBehavior}\`  
**Overall Confidence:** **${session.overallConfidence || 'High confidence'}**

---

## 1. Executive Summary & Root Cause

${session.aiAnalysisSummary || 'Forensic Dalvik bytecode analysis conducted over uploaded application artifacts.'}

**Root Cause Hypothesis:**  
${session.aiRootCause || 'Unwanted behavior identified through method tracing and intent sink analysis.'}

- **Observed Symptom:** ${session.observedBehavior || 'Unprompted modal or redirect'}
- **Expected Baseline:** ${session.expectedBehavior || 'Standard application flow'}

---

## 2. Evidence & Artifact Inventory

Total Artifacts Analyzed: **${session.artifacts.length}**  
Extracted Classes: **${session.parsedClasses.length}**  
Discovered URL Chains: **${session.urlChains.length}**  
Identified Findings: **${session.findings.length}**

| Artifact Name | Format | Size | Analysis Coverage | Status |
|---|---|---|---|---|
${session.artifacts
  .map(
    (a) =>
      `| \`${a.name}\` | \`${a.format}\` | ${(a.size / 1024).toFixed(1)} KB | ${a.coverage} | ${a.status.toUpperCase()} |`
  )
  .join('\n')}

${
  session.manifest
    ? `### Manifest Metadata
- **Package:** \`${session.manifest.packageName}\`
- **Version:** \`${session.manifest.versionName || 'N/A'}\` (code: \`${session.manifest.versionCode || 'N/A'}\`)
- **Permissions:** ${session.manifest.permissions.map((p) => `\`${p}\``).join(', ') || 'None requested'}
- **Components:** ${session.manifest.components.length} registered activities/services
`
    : ''
}

---

## 3. Forensic Behavioral Findings

${session.findings
  .map(
    (f, idx) => `### Finding ${idx + 1}: ${f.title}
- **Confidence Level:** \`${f.confidence}\`
- **Severity Rating:** \`${f.severity}\`
- **Target File:** \`${f.targetFile}\` (Class: \`${f.className}\`)
- **Method Signature:** \`${f.methodName}\` (Lines: \`${f.lineRange}\`)
- **Triggering Event:** ${f.triggeringEvent}
- **URL / Data Origin:** \`${f.urlOrigin}\`

#### Evidence Excerpt (Dalvik Smali Bytecode):
\`\`\`smali
${f.evidenceExcerpt}
\`\`\`

#### Execution Path Trace:
${f.executionPath.map((step, i) => `${i + 1}. ${step}`).join('\n')}

#### Rigorous Forensic Evaluation:
- **Rationale:** ${f.rationale}
- **Alternative Explanations:** ${f.alternativeExplanations}
- **Missing Evidence:** ${f.missingEvidence}
- **Recommended Verification Step:** ${f.recommendedInspection}

${
  f.remediation
    ? `#### Remediation Proposal (Minimal Safe Patch):
${f.remediation.description}
\`\`\`smali
${f.remediation.safePatchSmali}
\`\`\`
- **Control Flow Risks:** ${f.remediation.risks}
- **Regression Test:** ${f.remediation.regressionTest}
`
    : '_No remediation required (benign standard navigation)._'
}
`
  )
  .join('\n---\n')}

---

## 4. URL Provenance & Navigation Sinks

${
  session.urlChains.length === 0
    ? '_No URL navigation chains detected in parsed classes._'
    : session.urlChains
        .map(
          (c, idx) => `### Chain ${idx + 1}: \`${c.url}\`
- **Provenance Status:** \`${c.provenanceStatus.toUpperCase()}\`
- **Origin Type:** \`${c.originType}\` (Source: ${c.originSource})
- **Transformations:** ${c.transformations.join(' → ') || 'Direct literal pass'}
- **Navigation Sink:** \`${c.navigationSink}\`
- **Intermediate Methods:**
${c.intermediateMethods.map((m) => `  - \`${m}\``).join('\n')}
`
        )
        .join('\n')
}

---

## 5. Verification & Mobile Testing Plan

1. **Static Validation:** Verify modified Smali re-assembles cleanly with \`smali.jar\` or \`apktool\`. Ensure register counts and branch labels align.
2. **Dalvik Verifier Check:** Install patched APK on an emulator; verify \`VerifyError\` or \`ClassCastException\` are not thrown during class loading.
3. **Touch & Navigation Test:** Verify all main menus, back buttons, and standard workflows function without freezing or crashes.
4. **Logcat Monitoring:** Run \`adb logcat -s ActivityTaskManager:I Intent:I\` to confirm no unexpected background intents fire unprompted.

---
*Report generated by DroidForensics Workbench.*
`;
}
